import * as vscode from "vscode";
import { SidebarMessage } from "../../types/sidebarMessage";
import { APIService } from "../../services/APIService";
import { GitService } from "../../services/gitService";
import { waitUntil } from "../../utils/wait";

export class ProjectIndexingHandler {

    private readonly apiService = new APIService();
    private readonly gitService = new GitService();

    constructor(
        private readonly view: vscode.WebviewView        
    ) {}

    public async handle(message: SidebarMessage) {
        await this.gitService.initialize();
        console.log(message.command);

        let projectId = vscode.workspace.getConfiguration("vision").get<string>("projectId", "");
        const branch = vscode.workspace.getConfiguration("vision").get<string>("branch", 'None');
        const repo = await this.gitService.getRepositoryInfo(); 
        const remote = repo?.remote; 
        this.view.webview.postMessage({
            command: "briefStatus",
            data: false
        });
        const auto_briefing = await vscode.window.showInformationMessage("인덱싱과 함께 브리핑 생성도 요청하시겠습니까?", "예", "아니오");

        const body = {
            remote: remote,
            project_id: projectId,
            branch: branch,
            profile: {
                chunker: "ast-v3",
                context_header: true,
                use_bm25: true
            },
            briefing: auto_briefing === "예" ? "always" : true,
            model: vscode.workspace.getConfiguration("vision").get("modelId"),
            note: `${projectId} generated by Vision Extension`
        };
        console.log(body);
        try {
            const response: any = await this.apiService.post("/index", body, 60 * 1000);
            if (!response) {
                throw new Error("서버가 응답하지 않습니다.");
            }
            const state = await response.state;
            if (state === "done") {
                vscode.window.showInformationMessage("프로젝트 인덱싱이 완료되었습니다.");
                this.view.webview.postMessage({
                    command: "indexingDone"
                }); 
            } else if (state === "running") {
                this.view.webview.postMessage({
                    command: "indexingRunning"
                });
                vscode.window.showInformationMessage("프로젝트 인덱싱이 진행 중입니다.");
                waitUntil(
                    async () => await this.isIndexed(this.view, projectId, branch), 
                    10 * 60 * 1000, 100
                ).then(async (indexed) => {
                    if (!indexed) {
                        const rsp: any = await this.apiService.get(`/index/status?project_id=${projectId}`);
                        const error = rsp.error;
                        vscode.window.showErrorMessage("프로젝트 인덱싱이 실패했습니다: " + (error || rsp?.message || 'Unknown error'));
                        this.view.webview.postMessage({
                            command: "indexingError",
                            data: error || rsp?.message || "Server Error"
                        });
                        return;
                    }
                    vscode.window.showInformationMessage("프로젝트 인덱싱이 완료되었습니다.");
                    this.view.webview.postMessage({
                        command: "indexingDone"
                    });
                    waitUntil(
                        async () => await this.isBriefReady(projectId, branch), 
                        10 * 60 * 1000, 30 * 1000
                    ).then((briefReady) => {
                        if (!briefReady) {
                            vscode.window.showErrorMessage("프로젝트 브리핑이 시간 내에 준비되지 않았습니다.");
                            this.view.webview.postMessage({
                                command: "briefStatus",
                                data: false
                            });
                            return;
                        } 
                        vscode.window.showInformationMessage("프로젝트 브리핑이 준비되었습니다.");
                        this.view.webview.postMessage({
                            command: "briefStatus",
                            data: true
                        });
                    }).catch(() => {
                        vscode.window.showErrorMessage("프로젝트 브리핑 상태 확인 중 오류가 발생했습니다.");
                        this.view.webview.postMessage({
                            command: "briefStatus",
                            data: false
                        });
                    });
                }).catch(() => {
                    throw new Error("프로젝트 인덱싱 중 오류가 발생했습니다.");
                });                
            } else {
                throw new Error(response.error || "Unknown error occurred during project indexing.");
            }
        } catch (error) {
            console.error(error);
            vscode.window.showErrorMessage(`프로젝트 인덱싱 중 오류가 발생했습니다. ${error}`);
            this.view.webview.postMessage({
                command: "indexingError",
                data: error || "Unknown error occurred during project indexing."
            });
        }        
    }

    private async isIndexed(
        view: vscode.WebviewView, 
        projectId: string,
        branch: string,
    ): Promise<Boolean | undefined> {
        try {
            if (branch !== 'None') {
                projectId = projectId + '@' + branch;
            }
            const response: any = await this.apiService.get(
                `/index/status?project_id=${projectId}`
            );
            const state = response.state;
            console.log("indexing status: ", state);
            switch (state) {
                case "running":
                    const rate = response.total > 0 ? response.processed / response.total : 0;
                    view.webview.postMessage({
                        command: "indexingStatus",
                        data: rate
                    });
                    return undefined;
                case "done":
                    return true;
                case "failed":
                    return false;
                default:
                    return undefined;
            }
        } catch (error) {
            return undefined;
        }
    }
    
    private async isBriefReady(
        projectId: string, branch: string
    ): Promise<Boolean | undefined> {
        try {
            if (branch !== 'None') {
                projectId = projectId + '@' + branch;
            }
            const response:any = await this.apiService.get(
                `/index/status?project_id=${projectId}`
            );
            const isBriefReady = response.briefing;
            switch (isBriefReady) {
                case "ready":
                    return true;
                case "kept":
                    return true;
                default:
                    return undefined;
            }
        } catch (error) {
            return undefined;
        }
    }
}